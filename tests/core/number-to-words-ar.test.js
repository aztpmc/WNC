'use strict';
const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const N = require('../../src/core/index.js').default;

function ar(input, cur) { const r = N.convertAmount(input, cur); return r.ok ? r.arabic : 'ERR:' + r.code; }

describe('numberToArabicWords — core number grammar (masculine noun)', () => {
  const cases = [
    ['0', 'صفر'], ['1', 'واحد'], ['2', 'اثنان'], ['3', 'ثلاثة'], ['10', 'عشرة'],
    ['11', 'أحد عشر'], ['12', 'اثنا عشر'], ['19', 'تسعة عشر'], ['20', 'عشرون'],
    ['21', 'واحد وعشرون'], ['22', 'اثنان وعشرون'], ['99', 'تسعة وتسعون'],
    ['100', 'مئة'], ['101', 'مئة وواحد'], ['102', 'مئة واثنان'], ['103', 'مئة وثلاثة'],
    ['110', 'مئة وعشرة'], ['111', 'مئة وأحد عشر'], ['112', 'مئة واثنا عشر'],
    ['200', 'مئتان'], ['300', 'ثلاثمئة'], ['900', 'تسعمئة'], ['999', 'تسعمئة وتسعة وتسعون'],
    ['1000', 'ألف'], ['1001', 'ألف وواحد'], ['2000', 'ألفان'], ['3000', 'ثلاثة آلاف'],
    ['10000', 'عشرة آلاف'], ['100000', 'مئة ألف'],
    ['999999', 'تسعمئة وتسعة وتسعون ألفاً وتسعمئة وتسعة وتسعون'],
    ['1000000', 'مليون'], ['2000000', 'مليونان'], ['1000000000', 'مليار']
  ];
  for (const [n, want] of cases) {
    it(`${n} -> "${want}"`, () => assert.equal(N.numberToArabicWords(BigInt(n), 'm'), want));
  }
});

